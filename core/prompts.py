def numbered(items: list[str]) -> str:
    """Render a list for prompt injection."""
    return "\n".join(f"{i}. {item}" for i, item in enumerate(items, start=1)) or "—"


def render_transcript(turns: list[tuple[str, str]]) -> str:
    labels = {"interviewer": "Интервьюер", "candidate": "Кандидат"}
    return "\n\n".join(f"{labels.get(role, role)}: {text}" for role, text in turns)
